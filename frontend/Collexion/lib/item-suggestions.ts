// Search by text, so "destiny" finds "Destiny: The Taken King Limited Edition".
export const filterSuggestions = (list: string[], text: string): string[] => {
  const query = text.trim().toLowerCase();
  if (!query) return [];
  const results = list.filter((s) => s.toLowerCase().includes(query));
  // Hide the list when the user has already typed an exact match.
  if (results.length === 1 && results[0].toLowerCase() === query) return [];
  return results.slice(0, 8);
};

export const getModelSuggestions = (itemName: string): string[] =>
  Object.keys(itemSuggestions[itemName] ?? {});

// Only editions for the chosen model; if the model is unknown, show all of the item's editions.
export const getEditionSuggestions = (
  itemName: string,
  model: string,
): string[] => {
  const models = itemSuggestions[itemName];
  if (!models) return [];
  const key = Object.keys(models).find(
    (m) => m.toLowerCase() === model.trim().toLowerCase(),
  );
  if (key) return models[key];
  return Array.from(new Set(Object.values(models).flat()));
};
